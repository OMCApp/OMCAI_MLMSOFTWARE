 *
 * ‼️ ค่าที่ฟอร์มส่งกลับมา ต้อง validate ซ้ำฝั่ง server เสมอ (standard/security.md ข้อ 4ก)
 *    combobox เปลี่ยนค่าใน DOM ได้ง่ายกว่า select ธรรมดา — เชื่อว่า id ที่ได้มาอยู่ในรายการที่อนุญาตไม่ได้
