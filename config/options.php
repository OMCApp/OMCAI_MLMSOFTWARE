 *   hint    คอลัมน์รอง แสดงตัวเล็กใต้ label (ไม่มีก็ไม่ต้องใส่) — ช่วยแยกคนชื่อซ้ำกัน
 *   search  คอลัมน์ที่ยอมให้ค้น (allowlist)
 *   where   เงื่อนไขตายตัว เช่นเอาเฉพาะที่ยังใช้งานอยู่
 *   order   คอลัมน์ที่ใช้เรียง
 *   roles   บทบาทที่ค้นแหล่งนี้ได้ · ว่าง = ทุกคนที่ล็อกอิน
