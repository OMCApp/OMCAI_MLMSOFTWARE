 * ‼️ `roles` คือสิทธิ์ของแหล่งข้อมูลนั้น บังคับที่ OptionAccessMiddleware ที่เดียว (กฎเหล็กข้อ 4)
 *    ว่างไว้ = ผู้ใช้ที่ล็อกอินแล้วทุกคนค้นได้ · dropdown ของข้อมูลที่ไม่ควรให้ทุกคนเห็น ต้องใส่เสมอ
