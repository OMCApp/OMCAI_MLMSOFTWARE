<h2>Who can use this</h2>
<p>Administrators only</p>

<h2>Steps</h2>
<ol>
  <li>Open the <strong>Activity history</strong> menu</li>
  <li>Filter by action type, user, or date range</li>
  <li>Click a column header to sort by time or type</li>
  <li>Export to CSV if you need a record of it</li>
</ol>

<h2>Common problems</h2>
<ul>
  <li>History cannot be edited or deleted, not even by an administrator. That is deliberate: if it could be changed it would be worthless</li>
  <li>Simply viewing a page is not recorded. Only create, update, delete, and sign-in events are</li>
  <li>Entries older than the retention policy are moved to an archive, not deleted</li>
</ul>
