<h2>Who can use this</h2>
<p>Administrators only</p>

<h2>Steps</h2>
<ol>
  <li>Open the <strong>Reported issues</strong> menu and filter by status or type</li>
  <li>Press the view icon to open a report</li>
  <li>Review the context the system captured: the URL the user was on, their language, their theme, and the error reference</li>
  <li>Change the status, add an admin note, and save</li>
</ol>

<h2>Common problems</h2>
<ul>
  <li>When you answer a how-to question, add the answer to the manual article as well. Answering only in the ticket means the next person asks the same thing again</li>
  <li>At the bottom of the list page you will find the manual articles asked about most often. Those are the ones to fix first</li>
  <li>Admin notes are never shown to the person who reported the issue</li>
</ul>
