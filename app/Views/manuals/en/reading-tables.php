<h2>Who can use this</h2>
<p>Any signed-in user</p>

<h2>Steps</h2>
<ol>
  <li>Use the filter fields above the table to narrow down the rows</li>
  <li>When a table has a date range filter, use the shortcuts <strong>Today · This week · This month · 6 months · 1 year</strong></li>
  <li>Click a column header to sort. Click again to flip between ascending and descending</li>
  <li>Choose how many rows to show per page from the selector above</li>
  <li>Press <strong>Export CSV</strong> to download the rows matching your current filters</li>
</ol>

<h2>Common problems</h2>
<ul>
  <li>The export looks incomplete because it only contains rows matching the current filters. Clear the filters first if you want everything</li>
  <li>You can copy the URL of a filtered page and send it to someone else. They will see the same data</li>
  <li>On mobile the table becomes cards, so there is no need to scroll sideways</li>
</ul>
