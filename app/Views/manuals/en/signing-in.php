<h2>Who can use this</h2>
<p>Anyone with an account created by an administrator</p>

<h2>Steps</h2>
<ol>
  <li>Enter your username and password</li>
  <li>Press <strong>Sign in</strong></li>
</ol>

<h2>Common problems</h2>
<ul>
  <li>After several failed attempts the system pauses sign-in for a while. Wait a moment and try again</li>
  <li>The message never says whether the username or the password was wrong. That is deliberate so outsiders cannot learn which accounts exist</li>
</ul>
