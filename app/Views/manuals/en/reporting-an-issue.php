<h2>Who can use this</h2>
<p>Anyone, even without signing in</p>

<h2>Steps</h2>
<ol>
  <li>Press the question-mark button at the bottom left</li>
  <li>Choose <strong>Report a bug</strong>, <strong>Request a feature</strong>, or <strong>How do I use this</strong></li>
  <li>For how-to questions the system opens the manual for the page you are on first. Ask an admin only if that did not answer it</li>
  <li>Describe the issue, attach a screenshot if you have one, and send</li>
</ol>

<h2>Common problems</h2>
<ul>
  <li>You do not need to type which page you were on or what time it happened. The system records that automatically, including the most recent error reference</li>
  <li>If you saw a reference code such as ERR-7X4K2 on screen, include it. It makes finding the cause much faster</li>
  <li>You can send at most 5 reports per hour to prevent accidental duplicates</li>
</ul>
