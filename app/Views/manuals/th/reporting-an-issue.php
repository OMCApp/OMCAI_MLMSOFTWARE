<h2>ต้องมีสิทธิ์อะไร</h2>
<p>ทุกคน แม้ยังไม่ได้เข้าสู่ระบบ</p>

<h2>ขั้นตอน</h2>
<ol>
  <li>กดปุ่มเครื่องหมายคำถามมุมล่างซ้าย</li>
  <li>เลือกประเภท <strong>แจ้งบัค</strong> <strong>ขอเพิ่มฟีเจอร์</strong> หรือ <strong>วิธีใช้งาน</strong></li>
  <li>ถ้าเลือกวิธีใช้งาน ระบบจะพาไปคู่มือของหน้าที่กำลังเปิดอยู่ก่อน ถ้ายังไม่ได้คำตอบค่อยส่งถามผู้ดูแล</li>
  <li>อธิบายเรื่องที่ต้องการแจ้ง แนบภาพหน้าจอได้ถ้ามี แล้วกดส่ง</li>
</ol>

<h2>ข้อผิดพลาดที่พบบ่อย</h2>
<ul>
  <li>ไม่ต้องกรอกว่าอยู่หน้าไหนหรือเกิดตอนกี่โมง ระบบเก็บให้อัตโนมัติแล้ว รวมถึงรหัสอ้างอิงข้อผิดพลาดล่าสุด</li>
  <li>ถ้าเห็นรหัสอ้างอิงเช่น ERR-7X4K2 บนหน้าจอ ให้แจ้งรหัสนั้นมาด้วยจะช่วยให้หาสาเหตุได้เร็วขึ้นมาก</li>
  <li>ส่งได้ไม่เกิน 5 ครั้งต่อชั่วโมง เพื่อกันการส่งซ้ำโดยไม่ตั้งใจ</li>
</ul>
