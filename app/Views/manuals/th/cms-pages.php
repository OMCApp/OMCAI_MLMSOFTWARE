<h2>สิทธิ์ที่ต้องมี</h2>
<p>ผู้ดูแลระบบ และผู้แก้ไขเนื้อหา</p>

<h2>ขั้นตอน</h2>
<ol>
  <li>เข้าเมนู <strong>หน้าเว็บ</strong> แล้วกดชื่อหน้าที่ต้องการ หรือกด <strong>เพิ่มหน้า</strong></li>
  <li>กรอกชื่อเรื่องและ URL (ขึ้นต้นและลงท้ายด้วย /)</li>
  <li>ในส่วน <strong>บล็อกของหน้า</strong> เลือกชนิดบล็อกแล้วกดเพิ่ม กรอกข้อความ เลือกรูปจากคลังสื่อ ใช้ลูกศรเลื่อนขึ้นลง</li>
  <li>กรอก SEO title และ meta description ดูตัวนับตัวอักษรและตัวอย่างผลค้นหา</li>
  <li>กด <strong>บันทึก</strong> แล้วกด <strong>ดูตัวอย่าง</strong> เพื่อตรวจหน้าก่อนเผยแพร่</li>
  <li>เปลี่ยนสถานะเป็น <strong>เผยแพร่</strong> แล้วบันทึกอีกครั้ง</li>
  <li>ต้องการหน้าภาษาอื่น กด <strong>สร้างคำแปล</strong> ในแผงภาษาอื่น ระบบสร้างฉบับร่างใต้ /en/ หรือ /zh/ ให้</li>
</ol>

