<h2>ข้อผิดพลาดที่พบบ่อย</h2>
<ul>
  <li>เปลี่ยน URL ของหน้าที่เผยแพร่แล้ว — ให้ติ๊ก "สร้าง redirect 301 จาก URL เดิม" ไว้เสมอ ไม่งั้นลิงก์เดิมและอันดับ Google หาย</li>
  <li>ตัวเลขและโลโก้ลูกค้าไม่ได้กรอกในบล็อก — ใส่ที่ <strong>ตั้งค่าเว็บ</strong> และติ๊ก "ยืนยันแล้ว" ก่อนจึงขึ้นเว็บ</li>
  <li>ย้อนเนื้อหาเก่า: เปิด <strong>ประวัติการแก้ไข</strong> ด้านล่าง เลือกฉบับ แล้วกดย้อนกลับ (URL และสถานะไม่เปลี่ยน)</li>
</ul>
