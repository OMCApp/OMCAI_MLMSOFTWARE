<h2>สิทธิ์ที่ต้องมี</h2>
<p>ผู้ดูแลระบบ (เปลี่ยนรหัสผ่านของตัวเอง: ทุกคน)</p>

<h2>ขั้นตอน</h2>
<ol>
  <li>เข้าเมนู <strong>ผู้ใช้</strong> → <strong>เพิ่มผู้ใช้</strong> กรอกชื่อผู้ใช้ ชื่อที่แสดง บทบาท และรหัสผ่านเริ่มต้น</li>
  <li>บทบาท: ผู้ดูแลระบบ = ทุกอย่าง · ผู้แก้ไขเนื้อหา = เนื้อหา SEO สื่อ เมนู FAQ · ฝ่ายขาย = Lead เท่านั้น</li>
  <li>ผู้ใช้ใหม่ต้องเปลี่ยนรหัสผ่านเองตอนเข้าระบบครั้งแรก</li>
  <li>ปิดบัญชี: เอาติ๊ก "เปิดใช้งาน" ออกแล้วบันทึก มีผลทันที</li>
  <li>เปลี่ยนรหัสผ่านของตัวเอง: หน้าภาพรวม → <strong>เปลี่ยนรหัสผ่าน</strong></li>
</ol>

