<h2>สิทธิ์ที่ต้องมี</h2>
<p>ผู้ดูแลระบบ และฝ่ายขาย</p>

<h2>ขั้นตอน</h2>
<ol>
  <li>เข้าเมนู <strong>ผู้สนใจ (Lead)</strong> กรองตามสถานะ ฟอร์ม ช่วงวันที่ ภาษา หรือแหล่งที่มา (UTM, หน้าแรกที่เข้า, referrer)</li>
  <li>กดไอคอนดูเพื่อเปิดรายละเอียดทุกช่องที่ลูกค้ากรอก</li>
  <li>เปลี่ยนสถานะ (ใหม่ → ติดต่อแล้ว → มีโอกาส → ปิดการขาย/ไม่สำเร็จ) และเลือกผู้รับผิดชอบ แล้วบันทึก</li>
  <li>จดโน้ตทุกครั้งที่ติดต่อลูกค้า</li>
  <li>กด <strong>ส่งออก</strong> เพื่อได้ไฟล์ CSV ตามตัวกรองที่ใช้อยู่ เปิดด้วย Excel ได้ภาษาไทยถูกต้อง</li>
</ol>

