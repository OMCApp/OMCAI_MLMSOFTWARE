<h2>อีเมลแจ้งทีมขาย</h2>
<p>ทุก Lead บันทึกในระบบก่อนเสมอ แล้วระบบจึงส่งอีเมลแจ้งไปที่ <strong>อีเมลรับแจ้ง Lead</strong> (ตั้งค่าเว็บ) · คอลัมน์ <strong>อีเมลแจ้ง</strong> บอกผล</p>
<ul>
  <li><strong>ส่งแล้ว</strong> — ทีมขายได้อีเมลแล้ว</li>
  <li><strong>ส่งไม่สำเร็จ</strong> — Lead ยังอยู่ครบ แต่ทีมขายไม่ได้อีเมล · หน้าภาพรวมจะเตือนจนกว่าจะส่งได้ · กด <strong>ส่งอีเมลที่ค้างอีกครั้ง</strong> (ระบบลองส่งให้เองด้วยเมื่อมี Lead ใหม่ส่งสำเร็จ) · เปิดรายละเอียด Lead เพื่อดูสาเหตุ</li>
  <li><strong>ไม่ได้ส่ง (ปิดอีเมล)</strong> — ยังไม่ได้ตั้งค่าเซิร์ฟเวอร์อีเมล ให้เปิดหน้านี้เป็นประจำ</li>
</ul>
<p>ผู้ดูแลระบบทดสอบได้ที่ <strong>ตั้งค่าเว็บ → อีเมลแจ้ง Lead → ส่งอีเมลทดสอบ</strong> (ทำทุกครั้งหลังเปลี่ยนค่าอีเมล)</p>

<h2>ข้อผิดพลาดที่พบบ่อย</h2>
<ul>
  <li>อีเมลแจ้งไปอยู่ในโฟลเดอร์สแปม — ให้ผู้ดูแลโดเมนตั้ง SPF/DKIM ของอีเมลผู้ส่ง</li>
  <li>โน้ตแก้หรือลบไม่ได้ — ตรวจก่อนกดเพิ่ม</li>
  <li>ผู้รับผิดชอบเลือกได้เฉพาะผู้ดูแลระบบและฝ่ายขายที่ใช้งานอยู่</li>
  <li>ไฟล์ CSV มีข้อมูลส่วนตัวของลูกค้า เก็บให้ปลอดภัย</li>
</ul>
