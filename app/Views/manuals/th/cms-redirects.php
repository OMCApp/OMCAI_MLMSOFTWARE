<h2>ข้อผิดพลาดที่พบบ่อย</h2>
<ul>
  <li>ระบบไม่ยอมให้ redirect วนกลับมาที่เดิม</li>
  <li>ถ้าปลายทางเป็น redirect อีกทอด ระบบแจ้งปลายทางสุดท้าย — ติ๊ก "ชี้ไปปลายทางสุดท้ายแทน" แล้วบันทึกอีกครั้ง</li>
  <li>ใช้ 410 กับหน้าที่ลบถาวรและไม่มีหน้าทดแทน</li>
</ul>
