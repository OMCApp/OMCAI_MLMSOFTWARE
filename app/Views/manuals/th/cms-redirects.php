<h2>สิทธิ์ที่ต้องมี</h2>
<p>ผู้ดูแลระบบ และผู้แก้ไขเนื้อหา</p>

<h2>ขั้นตอน</h2>
<ol>
  <li>เข้าเมนู <strong>ลิงก์เสีย (404)</strong> ดู URL ที่มีคนเข้าแล้วไม่เจอ เรียงตามจำนวนครั้ง</li>
  <li>กดไอคอนลิงก์ของแถวนั้นเพื่อสร้าง redirect ระบบเติม URL ต้นทางให้</li>
  <li>กรอกปลายทาง เลือก 301 (ย้ายถาวร) แล้วบันทึก</li>
  <li>URL ที่ไม่สำคัญกดซ่อนได้</li>
  <li>redirect ทั้งหมดดูและแก้ได้ที่เมนู <strong>Redirect</strong></li>
</ol>

