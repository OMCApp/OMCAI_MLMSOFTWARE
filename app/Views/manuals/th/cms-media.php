<h2>สิทธิ์ที่ต้องมี</h2>
<p>ผู้ดูแลระบบ และผู้แก้ไขเนื้อหา</p>

<h2>ขั้นตอน</h2>
<ol>
  <li>เข้าเมนู <strong>คลังสื่อ</strong></li>
  <li>เลือกไฟล์ JPG PNG GIF หรือ WebP แล้วกรอก <strong>คำอธิบายรูป (alt)</strong> ซึ่งบังคับ</li>
  <li>กด <strong>อัปโหลดรูป</strong> — ระบบทำไฟล์ WebP และขนาดย่อยให้เอง</li>
  <li>กดรูปในตะแกรงเพื่อแก้ alt หรือดูว่ารูปถูกใช้ที่ไหน</li>
  <li>รูปเดิมของเว็บเก่ากด <strong>ลงทะเบียนรูปเดิมของเว็บเก่า</strong> แล้วเติม alt ให้รูปที่มีป้าย "ขาด alt"</li>
</ol>

