  <li>ลบรูปไม่ได้ถ้ายังถูกใช้อยู่ — หน้าแก้รูปบอกว่าใช้ที่ไหน ให้เอาออกจากที่นั้นก่อน</li>
  <li>alt ที่ดีบอกว่าในรูปมีอะไร ไม่ใช่ชื่อไฟล์</li>
</ul>
