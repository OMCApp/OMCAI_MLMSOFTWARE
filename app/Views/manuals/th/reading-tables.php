<h2>ต้องมีสิทธิ์อะไร</h2>
<p>ผู้ใช้ที่เข้าสู่ระบบแล้ว</p>

<h2>ขั้นตอน</h2>
<ol>
  <li>ใช้ช่องตัวกรองด้านบนตารางเพื่อจำกัดรายการที่ต้องการดู</li>
  <li>ถ้าตารางมีตัวกรองช่วงวัน ใช้ปุ่มลัด <strong>วันนี้ · สัปดาห์นี้ · เดือนนี้ · 6 เดือน · 1 ปี</strong> ได้ทันที</li>
  <li>กดที่หัวคอลัมน์เพื่อเรียงลำดับ กดซ้ำเพื่อสลับจากน้อยไปมากหรือมากไปน้อย</li>
  <li>เลือกจำนวนแถวที่แสดงต่อหน้าได้จากช่องด้านบน</li>
  <li>กด <strong>ส่งออก CSV</strong> เพื่อดาวน์โหลดข้อมูลตามตัวกรองที่ใช้อยู่</li>
</ol>

<h2>ข้อผิดพลาดที่พบบ่อย</h2>
<ul>
  <li>ส่งออก CSV แล้วได้ไม่ครบ เพราะไฟล์จะได้เฉพาะรายการที่ตรงกับตัวกรองที่ใช้อยู่เท่านั้น ล้างตัวกรองก่อนถ้าต้องการทั้งหมด</li>
  <li>ลิงก์ของหน้าที่กรองแล้วสามารถคัดลอกส่งให้คนอื่นเปิดดูข้อมูลชุดเดียวกันได้</li>
  <li>บนมือถือตารางจะแสดงเป็นการ์ดแทน ไม่ต้องเลื่อนตารางไปทางขวา</li>
</ul>
