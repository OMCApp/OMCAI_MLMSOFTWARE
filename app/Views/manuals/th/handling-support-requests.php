<h2>ต้องมีสิทธิ์อะไร</h2>
<p>ผู้ดูแลระบบเท่านั้น</p>

<h2>ขั้นตอน</h2>
<ol>
  <li>เข้าเมนู <strong>แจ้งปัญหา</strong> แล้วกรองตามสถานะหรือประเภท</li>
  <li>กดไอคอนดูรายละเอียดเพื่อเปิดเรื่องนั้น</li>
  <li>ดูบริบทที่ระบบเก็บให้ ทั้ง URL ที่ผู้ใช้อยู่ ภาษา โหมดแสดงผล และรหัสอ้างอิงข้อผิดพลาด</li>
  <li>เปลี่ยนสถานะและบันทึกหมายเหตุของผู้ดูแล แล้วกดบันทึก</li>
</ol>

<h2>ข้อผิดพลาดที่พบบ่อย</h2>
<ul>
  <li>คำถามประเภทวิธีใช้งานที่ตอบแล้ว ให้เอาคำตอบไปเติมในบทความคู่มือด้วย ไม่ใช่ตอบในเรื่องนั้นแล้วปิดไป ไม่งั้นคนต่อไปก็ถามซ้ำอีก</li>
  <li>ด้านล่างของหน้ารายการมีรายชื่อบทความที่ถูกถามต่อบ่อยที่สุด นั่นคือรายการที่ควรแก้ก่อน</li>
  <li>หมายเหตุของผู้ดูแลไม่แสดงให้ผู้ใช้เห็น</li>
</ul>
