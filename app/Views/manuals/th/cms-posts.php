  <li>บันทึก ดูตัวอย่าง แล้วเปลี่ยนสถานะเป็นเผยแพร่</li>
  <li>หมวดบทความจัดการได้ที่เมนู <strong>หมวดบทความ</strong> (ลบได้เฉพาะหมวดที่ไม่มีบทความ)</li>
