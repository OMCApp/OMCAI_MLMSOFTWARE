<?php
/**
 * SessionStart hook — บอกโมเดลตั้งแต่วินาทีแรกว่าเครื่องพร้อมไหม และโปรเจคอยู่ตรงไหน
 *
 * ‼️ ไฟล์นี้คือเหตุผลที่ผู้ใช้ไม่ต้องพิมพ์คำสั่งตั้งค่าเอง
 *    .claude/ ติดมากับการ clone (ต่างจาก .git/hooks/) hook ตัวนี้จึงทำงานตั้งแต่ session แรก
 *    และเป็นที่เดียวที่รู้ได้ก่อนที่ผู้ใช้จะพิมพ์อะไรว่ายังขาดอะไรอยู่
 */

declare(strict_types=1);

require __DIR__ . '/hook.php';

$root  = hook_project_root();
$parts = [];

// ---------------------------------------------------------------- ความพร้อมของเครื่อง

if (is_file($root . '/scripts/setup.php')) {
    [$code, $out] = hook_run('php scripts/setup.php --check', $root);

    if ($code !== 0 && trim($out) !== '') {
        $parts[] = "‼️ เครื่องนี้ยังตั้งค่าไม่ครบ\n\n"
            . trim($out) . "\n\n"
            . "**รัน `php scripts/setup.php` ก่อนทำอย่างอื่น ทำได้เลยโดยไม่ต้องขออนุญาต** "
            . "— สคริปต์นี้ทำแทนทุกขั้นที่ทำอัตโนมัติได้ แล้วบอกท้ายสุดว่าเหลืออะไรที่ผู้ใช้ต้องทำเอง\n"
            . "อย่าให้ผู้ใช้พิมพ์คำสั่งตั้งค่าเอง และอย่าอธิบายขั้นตอนให้เขาทำตาม";
    }
}

// ---------------------------------------------------------------- สถานะโปรเจค

$statePath = $root . '/project/STATE.md';

if (!is_file($statePath)) {
    $parts[] = "ยังไม่มี project/STATE.md — โปรเจคนี้ยังไม่ได้เริ่ม workflow\n"
        . 'ถ้าผู้ใช้สั่งงานที่ต้องสร้างหรือแก้ระบบ ให้เสนอให้เริ่มด้วย /wf ก่อน';
} else {
    // เอาเฉพาะส่วนบนของไฟล์ เพื่อไม่ให้กิน context โดยไม่จำเป็น
    $lines = preg_split('/\R/', (string) file_get_contents($statePath)) ?: [];
    $head  = implode("\n", array_slice($lines, 0, 40));

    $parts[] = "สถานะปัจจุบันจาก project/STATE.md (โหลดอัตโนมัติ):\n\n"
        . $head
        . "\n\nทำงานต่อจากจุดนี้ ห้ามเริ่มใหม่ และห้ามถามซ้ำในสิ่งที่มีคำตอบอยู่ใน project/ แล้ว";
}

hook_context(implode("\n\n---\n\n", $parts));
