<?php
/**
 * Phase 6 performance — WebP + responsive sizes for the images imported from WordPress
 *
 * Usage (from the project root, local database with migrations applied):
 *   php tools/media/build-legacy-webp.php
 *
 * For every media row under /wp-content/uploads/ (PNG/JPEG) without WebP sizes:
 *   · writes <name>.webp + <name>-480/768/1200/1600.webp next to the original (MediaService::webpVariants —
 *     the same converter the CMS uses on upload)
 *   · writes database/migrations/048_legacy_webp_sizes.sql that fills media.sizes for those rows on every
 *     environment (files go up with the FTP deploy; the server has no shell to run GD)
 *
 * ‼️ The original PNG/JPEG files stay — old URLs (backlinks, Google Images) keep working.
 * ‼️ The migration only sets sizes where it is still NULL — never overwrites a row changed in the CMS.
 * ‼️ 048 applied anywhere = do not regenerate with different content; later images go through the CMS.
 */

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    exit(1);
}

$root = dirname(__DIR__, 2);

require $root . '/core/autoload.php';
require $root . '/core/helpers.php';

/** @var array<string, mixed> $config */
$config = require $root . '/config/config.php';

if ($config['env'] === 'production') {
    fwrite(STDERR, "APP_ENV=production — run this locally\n");
    exit(1);
}

$GLOBALS['__config'] = $config;
Core\Logger::configure($config['paths']['log'], $config['debug']);
Core\Database::configure($config['db']);

$target = $root . '/database/migrations/048_legacy_webp_sizes.sql';
$rows   = Core\Database::select(
    "SELECT id, path, mime, bytes FROM media
      WHERE deleted_at IS NULL AND path LIKE '/wp-content/uploads/%' AND mime IN ('image/png', 'image/jpeg')
        AND (sizes IS NULL OR JSON_EXTRACT(sizes, '$.webp') IS NULL)
      ORDER BY path"
);

$service = new App\Services\MediaService();
$hex     = static fn (string $text): string => "CONVERT(X'" . strtoupper(bin2hex($text)) . "' USING utf8mb4)";
$sql     = "SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;\n\n"
    . "-- WebP + responsive sizes for the images imported from WordPress — generated by tools/media/build-legacy-webp.php\n"
    . "-- Files live next to the originals (public/wp-content/uploads/…). Only rows whose sizes are still NULL change.\n\n";

$before = 0;
$after  = 0;
$done   = 0;

foreach ($rows as $row) {
    $path  = (string) $row['path'];
    $sizes = $service->webpVariants($path);

    if (!isset($sizes['webp'])) {
        fwrite(STDERR, "skip (GD could not read): {$path}\n");
        continue;
    }

    $original = (int) filesize($root . '/public' . $path);
    $webp     = (int) filesize($root . '/public' . $sizes['webp']);
    $before  += $original;
    $after   += $webp;
    $done++;

    $json = json_encode($sizes, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    $sql .= "-- {$path}  ·  " . round($original / 1024) . ' KB → ' . round($webp / 1024) . " KB\n"
        . "UPDATE media SET sizes = {$hex($json)}, updated_at = NOW()\n"
        . "WHERE path = {$hex($path)} COLLATE utf8mb4_bin AND deleted_at IS NULL AND sizes IS NULL;\n\n";
}

file_put_contents($target, $sql);
printf("%d images · originals %.1f MB → full-size WebP %.1f MB\nwrote %s\n", $done, $before / 1048576, $after / 1048576, substr($target, strlen($root) + 1));
