/** @return list<array{src:string, alt:string, heading:string, caption:string}> */
function image_contexts(string $html): array
{
    [$doc, $xp] = dom_load('<div id="c">' . $html . '</div>');
    $out = [];
    $heading = '';
    foreach ($xp->query('//*[@id="c"]//*') as $el) {
        if (preg_match('/^h[2-6]$/', $el->tagName)) {
            $heading = trim(preg_replace('/\s+/u', ' ', $el->textContent));
        } elseif ($el->tagName === 'img') {
            $caption = '';
            for ($p = $el->parentNode; $p instanceof DOMElement; $p = $p->parentNode) {
                if ($p->tagName === 'figure') {
                    $caption = xp_first($xp, './/figcaption', $p);
                    break;
                }
            }
            $out[] = ['src' => html_entity_decode($el->getAttribute('src')), 'alt' => $el->getAttribute('alt'),
                'heading' => $heading, 'caption' => $caption];
        }
    }
    return $out;
}

/** Thai alt text built only from existing words on the page (caption → nearest heading → title). */
function suggest_alt(string $title, array $ctx, string $type): string
{
    if ($ctx['caption'] !== '') {
        return mb_substr($ctx['caption'], 0, 125);
    }
    if ($ctx['heading'] !== '') {
        return mb_substr('ภาพประกอบ: ' . $ctx['heading'], 0, 125);
    }
    return mb_substr(($type === 'post' ? 'ภาพประกอบบทความ ' : 'ภาพประกอบหน้า ') . $title, 0, 125);
}

function plain_text(string $html): string
{
    return trim(preg_replace('/\s+/u', ' ', html_entity_decode(strip_tags(str_replace('<', ' <', $html)), ENT_QUOTES, 'UTF-8')));
}

/** @return array<string, mixed> */
function ocpb_similarity(array $records): array
{
    $by = array_column($records, null, 'path_decoded');
    $a = $by['/ocpb-mlm/'] ?? null;
    $b = $by['/ocpb-mlm2/'] ?? null;
    if (!$a || !$b || !isset($a['content_html'], $b['content_html'])) {
        return ['error' => 'one of the pages missing'];
    }
    $shingles = function (string $html): array {
        $t = mb_strtolower(preg_replace('/[\s\p{P}]+/u', '', plain_text($html)));
        $set = [];
        $len = mb_strlen($t);
        for ($i = 0; $i + 5 <= $len; $i++) {
            $set[mb_substr($t, $i, 5)] = true;
        }
        return $set;
    };
    $sa = $shingles($a['content_html']);
    $sb = $shingles($b['content_html']);
    $inter = count(array_intersect_key($sa, $sb));
    $union = count($sa + $sb);

    $blocks = function (string $html): array {
        $set = [];
        foreach (explode("\n", $html) as $line) {
            $t = plain_text($line);
            if (mb_strlen($t) > 3) {
                $set[$t] = true;
            }
        }
        return $set;
    };
    $ba = $blocks($a['content_html']);
    $bb = $blocks($b['content_html']);
    $shared = count(array_intersect_key($ba, $bb));

    return [
        'text_chars' => [mb_strlen(plain_text($a['content_html'])), mb_strlen(plain_text($b['content_html']))],
        'jaccard_5gram_pct' => $union ? round(100 * $inter / $union, 1) : 0,
        'containment_ocpb_in_ocpb2_pct' => $sa ? round(100 * $inter / count($sa), 1) : 0,
        'containment_ocpb2_in_ocpb_pct' => $sb ? round(100 * $inter / count($sb), 1) : 0,
        'identical_blocks' => $shared,
        'blocks' => [count($ba), count($bb)],
        'titles' => [$a['title_clean'], $b['title_clean']],
        'descriptions_equal' => $a['meta_description'] === $b['meta_description'],
        'canonicals' => [$a['canonical'], $b['canonical']],
    ];
}

function md_cell(string $s): string
{
    return str_replace(['|', "\n"], ['\|', ' '], $s);
}

function summary_md(array $records, ?ImageMigrator $img, array $ocpb): string
{
    $md = "# Content extraction summary\n\n";
    $md .= "Generated by `tools/migration/extract.php` on " . date('Y-m-d H:i') . " from the live site (baseline `docs/seo/baseline-2026-11-03/pages.csv`).\n";
    $md .= "Full data: [`content.json`](content.json) · images: [`images.csv`](images.csv) · contact: [`contact-info.json`](contact-info.json) · page copy: [`pages-text.md`](pages-text.md)\n\n";

    $types = array_count_values(array_column($records, 'type'));
    $md .= "**Extracted:** " . ($types['post'] ?? 0) . " posts · " . ($types['page'] ?? 0) . " pages · " . ($types['category'] ?? 0) . " categories\n\n";
    $md .= "Content selector: posts `.seocrawler-single-article-content` · pages/categories `#seocrawler-page-wrapper` minus title bar, sidebars, blog/portfolio listing items, pagination, share/nav/comments.\n";
    $md .= "Words = whitespace-separated tokens (same as the SEO baseline; Thai has no spaces so this undercounts) · Chars = non-space characters.\n\n";

    $md .= "| Path | Type | Clean title | Desc len | H1 (live) | Date | Category | Words / chars | Images | Missing alt |\n";
    $md .= "|---|---|---|---|---|---|---|---|---|---|\n";
    foreach ($records as $r) {
        if (!isset($r['content_html'])) {
            $md .= '| ' . md_cell($r['path_decoded']) . ' | ' . $r['type'] . ' | FETCH FAILED |||||||' . "\n";
            continue;
        }
        $missing = count(array_filter($r['images'], fn ($i) => $i['alt'] === ''));
        $h1 = $r['h1'] === [] ? '—' : (count($r['h1']) > 1 ? count($r['h1']) . '× ' : '') . $r['h1'][0];
        $md .= sprintf("| %s | %s | %s | %s | %s | %s | %s | %d / %d | %d | %d |\n",
            md_cell($r['path_decoded']), $r['type'], md_cell($r['title_clean']),
            mb_strlen($r['meta_description']) ?: '**0**', md_cell(mb_substr($h1, 0, 70)),
            substr($r['published_at'], 0, 10) ?: '—',
            md_cell(implode(', ', array_column($r['categories'], 'name')) ?: '—'),
            $r['word_count'], $r['char_count'], count($r['images']), $missing);
    }

    $md .= "\n## ocpb-mlm vs ocpb-mlm2\n\n```json\n" . json_encode($ocpb, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . "\n```\n";

    if ($img) {
        $src = [];
        $bytesBy = [];
        foreach ($img->refs as $r) {
            $s = $r['source'] ?? '?';
            $src[$s] = ($src[$s] ?? 0) + 1;
            $bytesBy[$s] = ($bytesBy[$s] ?? 0) + (int) ($r['bytes'] ?? 0);
        }
        $md .= "\n## Images\n\n| Source | Files | MB |\n|---|---|---|\n";
        foreach ($src as $s => $n) {
            $md .= sprintf("| %s | %d | %.1f |\n", $s, $n, $bytesBy[$s] / 1048576);
        }
        $md .= sprintf("\nTotal copied into `public/wp-content/uploads/`: **%.1f MB**%s\n", $img->totalBytes / 1048576,
            $img->stopped ? ' — **stopped at the size limit**' : '');
    }

    $md .= "\n## Extraction problems per URL\n\n";
    $any = false;
    foreach ($records as $r) {
        if (!empty($r['problems'])) {
            $md .= '- `' . $r['path_decoded'] . '` — ' . implode('; ', $r['problems']) . "\n";
            $any = true;
        }
    }
    $md .= $any ? '' : "None.\n";

    if (is_file(MIGRATION_NOTES)) {
        $md .= "\n" . file_get_contents(MIGRATION_NOTES);
    }
    return $md;
}

function pages_text_md(array $records, array $paths): string
{
    $by = array_column($records, null, 'path_decoded');
    $md = "# Old page copy — section by section\n\n";
    $md .= "Extracted from the live site so copywriters can keep the keyword intent when rewriting. Headings are shown as `###`/`####` regardless of their original level (original level in brackets). Images are shown as `[ภาพ: alt]`. Duplicated slider / flip-box text has been removed.\n\n";
    foreach ($paths as $p) {
        $r = $by[$p] ?? null;
        if (!$r || !isset($r['content_html'])) {
            $md .= "## `$p`\n\n(not extracted)\n\n";
            continue;
        }
        $md .= "---\n\n## `$p` — " . ($r['title_clean'] ?: '(no title)') . "\n\n";
        $md .= "- **Title tag (raw, " . mb_strlen($r['title_raw']) . " chars):** " . mb_substr($r['title_raw'], 0, 160) . (mb_strlen($r['title_raw']) > 160 ? ' …' : '') . "\n";
        $md .= "- **Meta description:** " . ($r['meta_description'] ?: '_(none)_') . "\n";
        $md .= "- **H1:** " . ($r['h1'] ? implode(' · ', $r['h1']) : '_(none)_') . "\n\n";
        [$doc, $xp] = dom_load('<div id="c">' . $r['content_html'] . '</div>');
        foreach ($xp->query('//*[@id="c"]')->item(0)->childNodes as $n) {
            $md .= md_block($n);
        }
        $md .= "\n";
    }
    return $md;
}

function md_block(DOMNode $n): string
{
    if (!$n instanceof DOMElement) {
        $t = trim($n->textContent);
        return $t === '' ? '' : $t . "\n\n";
    }
    $text = fn (DOMNode $x) => trim(preg_replace('/\s+/u', ' ', $x->textContent));
    $imgs = function (DOMElement $x): string {
        $s = '';
        foreach ($x->getElementsByTagName('img') as $i) {
            $s .= '[ภาพ: ' . ($i->getAttribute('alt') ?: 'ไม่มี alt') . '] ';
        }
        return trim($s);
    };
    switch ($n->tagName) {
        case 'h2':
        case 'h3':
            return "\n### " . $text($n) . " [{$n->tagName}]\n\n";
        case 'h4':
        case 'h5':
        case 'h6':
            return "#### " . $text($n) . " [{$n->tagName}]\n\n";
        case 'ul':
        case 'ol':
            $s = '';
            foreach ($n->childNodes as $li) {
                if ($li instanceof DOMElement) {
                    $s .= '- ' . trim($text($li) . ' ' . $imgs($li)) . "\n";
                }
            }
            return $s . "\n";
        case 'table':
            $s = '';
            foreach ($n->getElementsByTagName('tr') as $tr) {
                $cells = [];
                foreach ($tr->childNodes as $td) {
                    if ($td instanceof DOMElement) {
                        $cells[] = $text($td);
                    }
                }
                $s .= '| ' . implode(' | ', $cells) . " |\n";
            }
            return $s . "\n";
        default:
            $t = trim($text($n) . ' ' . $imgs($n));
            return $t === '' ? '' : $t . "\n\n";
    }
}
