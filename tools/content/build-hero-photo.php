<?php
/**
 * Home hero person photo, mockup 2026-11-04 rev. 2 — writes database/migrations/046_hero_executive_photo.sql
 *
 * Usage: php tools/content/build-hero-photo.php
 *
 * Photo: public/assets/images/stock/hero-executive{,-768,-480}.webp — Unsplash F_CnS-8NlZQ (Humberto Chávez,
 * Unsplash License: commercial use, no credit required). Background removed so it sits on the warm hero;
 * illustrative only — the page labels it and the alt text never claims an OMC employee.
 *
 * What the migration does
 *   · registers the photo in the media library (the CMS image picker finds it)
 *   · replaces hero.person on /, /en/, /zh/ ONLY while it is still the 044 stock photo —
 *     a photo already changed in the CMS is left alone
 * ‼️ 044 is applied on staging — never regenerate it; later photo changes go through the CMS or a new migration.
 */

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    exit(1);
}

$root   = dirname(__DIR__, 2);
$target = $root . '/database/migrations/046_hero_executive_photo.sql';
$name   = 'hero-executive';
$old    = '/assets/images/stock/hero-consultant.webp';

$alt = [
    'th' => 'ภาพประกอบ ผู้บริหารธุรกิจในชุดสูทสีกรมท่า',
    'en' => 'Illustrative photo of a business executive in a navy suit',
    'zh' => '示意图片：身穿藏青色西装的企业高管',
];
$paths = ['th' => '/', 'en' => '/en/', 'zh' => '/zh/'];

$file = $root . "/public/assets/images/stock/{$name}.webp";
$info = getimagesize($file);
if ($info === false) {
    fwrite(STDERR, "missing {$file}\n");
    exit(1);
}

$srcset = [];
foreach ([480, 768] as $width) {
    if (is_file($root . "/public/assets/images/stock/{$name}-{$width}.webp")) {
        $srcset[$width] = "/assets/images/stock/{$name}-{$width}.webp";
    }
}
$src             = "/assets/images/stock/{$name}.webp";
$srcset[$info[0]] = $src;

$hex = static fn (string $text): string => "CONVERT(X'" . strtoupper(bin2hex($text)) . "' USING utf8mb4)";

$sizes = json_encode(['webp' => $src] + array_map('strval', $srcset), JSON_UNESCAPED_SLASHES);
$sql   = "SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;\n\n"
    . "-- Home hero person photo (mockup 2026-11-04 rev. 2) — generated by tools/content/build-hero-photo.php\n"
    . "-- Illustrative stock photo (Unsplash License), labelled on the page. Only replaces the 044 stock photo;\n"
    . "-- a hero photo already changed in the CMS is left alone.\n\n"
    . "-- media: {$name}\n"
    . "-- alt: {$alt['th']}\n"
    . "INSERT INTO media (path, mime, width, height, alt, title, sizes, bytes, created_at, updated_at)\n"
    . "SELECT '{$src}', 'image/webp', {$info[0]}, {$info[1]}, {$hex($alt['th'])}, '{$name}', '{$sizes}', " . filesize($file) . ", NOW(), NOW()\n"
    . "FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM media WHERE path = '{$src}' AND deleted_at IS NULL);\n\n";

foreach ($paths as $locale => $path) {
    $person = json_encode(
        ['src' => $src, 'alt' => $alt[$locale], 'width' => $info[0], 'height' => $info[1], 'srcset' => $srcset],
        JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
    );
    $sql .= "-- {$path}  ·  alt: {$alt[$locale]}\n"
        . "UPDATE pages SET blocks = JSON_SET(blocks, '\$[0].data.person', JSON_EXTRACT({$hex($person)}, '\$')), updated_at = NOW()\n"
        . "WHERE path = {$hex($path)} COLLATE utf8mb4_bin AND locale = '{$locale}' AND deleted_at IS NULL\n"
        . "  AND JSON_UNQUOTE(JSON_EXTRACT(blocks, '\$[0].type')) = 'hero'\n"
        . "  AND JSON_UNQUOTE(JSON_EXTRACT(blocks, '\$[0].data.person.src')) = '{$old}';\n\n";
}

file_put_contents($target, $sql);
echo 'wrote ' . substr($target, strlen($root) + 1) . "\n";
