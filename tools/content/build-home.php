<?php
/**
 * Home page in the layout of the approved mockup (2026-11-04) — writes database/migrations/044_home_mockup_layout.sql
 *
 * Usage (from the project root):
 *   php tools/content/build-home.php
 *
 * Input:  tools/content/home/<locale>.php (copy per locale)
 *         tools/content/<locale>/core.php '/' page — plan_cards / industry_grid items are reused from there
 *         public/assets/images/stock/*.webp — illustrative photos (Unsplash License, project/NOTES.md)
 *
 * Section order (mockup): hero (person + devices) · verified stats · why OMC (4 cards) · feature showcase ·
 *   plans · industries · team · steps · testimonials (consented only — hidden when empty) · contact (compact form)
 *
 * What the migration does
 *   · registers the three photos in the media library (path = WebP, so the CMS image picker finds them)
 *   · replaces pages.blocks of '/', '/en/', '/zh/' — title / SEO fields and URLs are NOT touched
 *   · internal links in en/zh point at the translated page when one exists (same rule as build-pages.php)
 *
 * ‼️ Deterministic output. Once 044 has been applied anywhere, never regenerate it with different content —
 *    later changes go through the CMS or a new migration.
 */

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    exit(1);
}

$root    = dirname(__DIR__, 2);
$target  = $root . '/database/migrations/044_home_mockup_layout.sql';
$locales = array_keys((array) require $root . '/config/locales.php');
$default = $locales[0];
$site    = (array) require $root . '/config/site.php';
$demoUrl = (string) ($site['cta']['url'] ?? '/demo/');

$hex = static fn (string $value): string => "CONVERT(X'" . strtoupper(bin2hex($value)) . "' USING utf8mb4)";

/* ---------------------------------------------------------------- photos */

$photos = [];
foreach (['hero-consultant', 'team', 'support'] as $name) {
    $file = $root . '/public/assets/images/stock/' . $name . '.webp';
    $info = getimagesize($file);
    if ($info === false) {
        fwrite(STDERR, "missing photo: {$file}\n");
        exit(1);
    }

    $srcset = [];
    foreach ([480, 768] as $width) {
        if (is_file($root . "/public/assets/images/stock/{$name}-{$width}.webp")) {
            $srcset[$width] = "/assets/images/stock/{$name}-{$width}.webp";
        }
    }
    $srcset[(int) $info[0]] = "/assets/images/stock/{$name}.webp";

    $photos[$name] = [
        'src'    => "/assets/images/stock/{$name}.webp",
        'width'  => (int) $info[0],
        'height' => (int) $info[1],
        'srcset' => $srcset,
        'bytes'  => (int) filesize($file),
    ];
}

$image = static function (string $name, array $content) use ($photos): array {
    return [
        'src'    => $photos[$name]['src'],
        'alt'    => (string) $content['media_alt'][$name],
        'width'  => $photos[$name]['width'],
        'height' => $photos[$name]['height'],
        'srcset' => $photos[$name]['srcset'],
    ];
};

/* ---------------------------------------------------------------- path map (thai path => translated path) */

$pathMap = static function (string $locale) use ($root): array {
    $map = [];
    foreach (glob($root . '/tools/content/' . $locale . '/*.php') ?: [] as $file) {
        foreach ((array) require $file as $thaiPath => $page) {
            if (is_array($page) && isset($page['path'])) {
                $map[(string) $thaiPath] = (string) $page['path'];
            }
        }
    }

    return $map;
};

$localize = static function ($value, array $map) use (&$localize) {
    if (is_array($value)) {
        foreach ($value as $key => $item) {
            $value[$key] = $key === 'url' && is_string($item) ? ($map[$item] ?? $item) : $localize($item, $map);
        }
    }

    return $value;
};

/* ---------------------------------------------------------------- blocks */

$sql = "SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;\n\n"
    . "-- Home page in the layout of the approved mockup (2026-11-04) — generated by tools/content/build-home.php\n"
    . "-- Photos are illustrative (Unsplash License) and labelled as such on the page; replace them in the CMS when real\n"
    . "-- team photos are available. Page title, SEO fields and URLs are unchanged.\n\n";

foreach ($photos as $name => $photo) {
    $alt   = (string) ((require $root . '/tools/content/home/' . $default . '.php')['media_alt'][$name]);
    $sizes = json_encode(['webp' => $photo['src']] + array_map('strval', $photo['srcset']), JSON_UNESCAPED_SLASHES);
    $sql  .= "-- media: {$name}\n"
        . "INSERT INTO media (path, mime, width, height, alt, title, sizes, bytes, created_at, updated_at)\n"
        . "SELECT '{$photo['src']}', 'image/webp', {$photo['width']}, {$photo['height']}, {$hex($alt)}, '{$name}', '{$sizes}', {$photo['bytes']}, NOW(), NOW()\n"
        . "FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM media WHERE path = '{$photo['src']}' AND deleted_at IS NULL);\n\n";
}

foreach ($locales as $locale) {
    $c      = (array) require $root . '/tools/content/home/' . $locale . '.php';
    $source = (array) ((require $root . '/tools/content/' . $locale . '/core.php')['/']['blocks'] ?? []);
    $byType = [];
    foreach ($source as $block) {
        $byType[$block['type']] ??= $block;
    }

    $blocks = [
        ['type' => 'hero'] + array_diff_key($c['hero'], ['demo' => 1, 'consult' => 1]) + [
            'actions' => [
                ['label' => $c['hero']['demo'], 'url' => $demoUrl, 'style' => 'primary', 'icon' => 'view'],
                ['label' => $c['hero']['consult'], 'url' => '#lead-form', 'style' => 'secondary', 'icon' => 'phone'],
            ],
            'person' => $image('hero-consultant', $c),
        ],
        ['type' => 'stats'],
        ['type' => 'feature_grid', 'columns' => '4'] + $c['why'],
        ['type' => 'dashboard_showcase', 'layout' => 'device', 'reverse' => true]
            + array_diff_key($c['showcase'], ['action' => 1])
            + ['action' => ['label' => $c['showcase']['action'], 'url' => '/features/']],
        array_merge($byType['plan_cards'], $c['plans'], ['eyebrow' => '']),
        array_merge($byType['industry_grid'], $c['industries'], ['eyebrow' => '']),
        ['type' => 'split', 'layout' => 'plain', 'visual' => 'image', 'reverse' => true, 'image' => $image('team', $c)]
            + array_diff_key($c['team'], ['action' => 1])
            + ['action' => ['label' => $c['team']['action'], 'url' => '/about/', 'style' => 'outline']],
        ['type' => 'steps'] + $c['steps'],
        ['type' => 'testimonials'] + $c['testimonials'],
        ['type' => 'lead_form', 'form_key' => 'consult', 'layout' => 'compact', 'image' => $image('support', $c)] + $c['contact'],
    ];

    if ($locale !== $default) {
        $blocks = $localize($blocks, $pathMap($locale));
    }

    $rows = array_map(
        static fn (array $block): array => ['type' => $block['type'], 'data' => array_diff_key($block, ['type' => 1])],
        $blocks
    );
    $json = json_encode($rows, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
    $path = $locale === $default ? '/' : '/' . $locale . '/';

    $sql .= "-- {$path}  ·  " . count($rows) . " blocks\n"
        . "UPDATE pages SET blocks = {$hex($json)}, updated_at = NOW()\n"
        . "WHERE path = {$hex($path)} COLLATE utf8mb4_bin AND locale = '{$locale}' AND deleted_at IS NULL;\n\n";
}

file_put_contents($target, rtrim($sql) . "\n");
echo 'wrote ' . substr($target, strlen($root) + 1) . "\n";
